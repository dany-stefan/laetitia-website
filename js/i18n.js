window.applyI18n = function (lang) {
  const dict = window.I18N[lang] || window.I18N.fr;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] != null) el.textContent = dict[key];
  });
  document.querySelectorAll(".lang-toggle button").forEach((btn) => {
    btn.setAttribute("aria-pressed", btn.dataset.lang === lang ? "true" : "false");
  });
  localStorage.setItem("ll-lang", lang);
  const auto = document.querySelector("[name=_autoresponse]");
  if (auto && dict.book_mail) auto.value = dict.book_mail;
  const langSel = document.getElementById("language");
  if (langSel && [...langSel.options].some((o) => o.value === lang)) langSel.value = lang;
};
